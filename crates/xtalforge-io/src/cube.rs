//! Gaussian cube volumetric data (Task 3.5.2).

#![allow(clippy::indexing_slicing)] // fixed-format parser, lengths checked above
use xtalforge_core::Error;

use crate::grid::Grid3;

/// Bohr radius in Angstrom.
pub const BOHR: f64 = 0.529_177_210_903;

/// Grid and atom centres read from a cube file.
pub type CubeData = (Grid3, Vec<(u8, [f64; 3])>);

/// Reads a Gaussian cube file.
///
/// A negative atom count means the voxel vectors are in Angstrom; the atom
/// coordinates are always in Bohr.
///
/// # Errors
///
/// Returns [`Error::InvalidInput`] for a short header, bad values or a data
/// count that does not match the grid shape.
pub fn read_cube(text: &str) -> Result<CubeData, Error> {
    let mut lines = text.lines();
    let _comment_a = lines.next();
    let _comment_b = lines.next();
    let counts: Vec<i64> = lines
        .next()
        .unwrap_or("")
        .split_whitespace()
        .filter_map(|value| value.parse().ok())
        .collect();
    if counts.len() < 4 {
        return Err(Error::InvalidInput(
            "a cube header needs an atom count and three dimensions".to_owned(),
        ));
    }
    let negative = counts[0] < 0;
    let atoms = counts[0].unsigned_abs() as usize;
    let shape = [
        counts[1].unsigned_abs() as usize,
        counts[2].unsigned_abs() as usize,
        counts[3].unsigned_abs() as usize,
    ];
    let unit = if negative { 1.0 } else { BOHR };
    let mut origin = [0.0; 3];
    let origin_line = lines.next().unwrap_or("");
    let origin_values: Vec<f64> = origin_line
        .split_whitespace()
        .filter_map(|v| v.parse().ok())
        .collect();
    if origin_values.len() < 3 {
        return Err(Error::InvalidInput("cube origin is incomplete".to_owned()));
    }
    for axis in 0..3 {
        origin[axis] = origin_values[axis] * BOHR;
    }
    let mut step = [[0.0; 3]; 3];
    for row in &mut step {
        let line = lines.next().unwrap_or("");
        let values: Vec<f64> = line
            .split_whitespace()
            .filter_map(|v| v.parse().ok())
            .collect();
        if values.len() < 4 {
            return Err(Error::InvalidInput(
                "a cube voxel line needs a count and three steps".to_owned(),
            ));
        }
        for (direction, value) in values.iter().skip(1).take(3).enumerate() {
            if let Some(slot) = row.get_mut(direction) {
                *slot = value * unit;
            }
        }
    }
    let mut atoms_out = Vec::with_capacity(atoms);
    for _ in 0..atoms {
        let line = lines.next().unwrap_or("");
        let values: Vec<f64> = line
            .split_whitespace()
            .filter_map(|v| v.parse().ok())
            .collect();
        if values.len() < 5 {
            return Err(Error::InvalidInput(
                "a cube atom line is incomplete".to_owned(),
            ));
        }
        atoms_out.push((
            values[0] as u8,
            [values[2] * BOHR, values[3] * BOHR, values[4] * BOHR],
        ));
    }
    let expected = shape[0] * shape[1] * shape[2];
    let mut data = Vec::with_capacity(expected);
    for line in lines {
        for value in line.split_whitespace() {
            if let Ok(number) = value.parse::<f64>() {
                data.push(number);
            }
        }
    }
    let grid = Grid3::new(origin, step, shape, data, false)?;
    Ok((grid, atoms_out))
}

/// Writes a cube file from a grid and atom centres.
///
/// # Errors
///
/// Returns [`Error::InvalidInput`] when the header cannot be represented.
pub fn write_cube(grid: &Grid3, atoms: &[(u8, [f64; 3])]) -> Result<String, Error> {
    if !grid.origin.iter().all(|value| value.is_finite()) {
        return Err(Error::InvalidInput("grid origin is not finite".to_owned()));
    }
    let mut out = String::new();
    out.push_str("xtalforge cube\n");
    out.push_str("generated by xtalforge\n");
    out.push_str(&format!(
        "{} {} {} {}\n",
        atoms.len(),
        grid.shape[0],
        grid.shape[1],
        grid.shape[2]
    ));
    out.push_str(&format!(
        "{:12.6} {:12.6} {:12.6}\n",
        grid.origin[0] / BOHR,
        grid.origin[1] / BOHR,
        grid.origin[2] / BOHR
    ));
    for axis in 0..3 {
        out.push_str(&format!(
            "{:5} {:12.6} {:12.6} {:12.6}\n",
            grid.shape[axis],
            grid.step[axis][0] / BOHR,
            grid.step[axis][1] / BOHR,
            grid.step[axis][2] / BOHR
        ));
    }
    for (z, point) in atoms {
        out.push_str(&format!(
            "{:5} {:12.6} {:12.6} {:12.6} {:12.6}\n",
            z,
            f64::from(*z),
            point[0] / BOHR,
            point[1] / BOHR,
            point[2] / BOHR
        ));
    }
    for chunk in grid.data.chunks(6) {
        let values: Vec<String> = chunk.iter().map(|value| format!("{value:12.5e}")).collect();
        out.push_str(&values.join(" "));
        out.push('\n');
    }
    Ok(out)
}
