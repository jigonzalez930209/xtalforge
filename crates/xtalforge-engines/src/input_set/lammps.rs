//! LAMMPS data and input-script writer (Task 18.1.5).
//!
//! The data file is the existing `xtalforge_io` LAMMPS writer. The input
//! script adds explicit `pair_coeff` and `bond_coeff` entries computed from the
//! native UFF/UFF4MOF tables in `xtalforge_ff`, so the parameters are the same
//! ones used by the in-process force field.

use std::collections::BTreeSet;

use xtalforge_core::{P1Cell, Structure};
use xtalforge_ff::uff::{ParameterSet, params, terms};

use crate::Error;
use crate::input_set::settings::Settings;
use crate::input_set::util;

const DATA: &str = "system.data";
const INPUT: &str = "input.lammps";

pub(crate) fn build(
    structure: &Structure,
    settings: &Settings,
) -> Result<Vec<super::InputFile>, Error> {
    let p1 = structure.p1()?;
    if p1.atoms.is_empty() {
        return Err(Error::Job(
            "LAMMPS needs a structure with at least one atom".to_owned(),
        ));
    }
    let parameter_set = match settings.text("parameter_set")? {
        "uff" => ParameterSet::Uff,
        "uff4mof" => ParameterSet::Uff4Mof,
        other => {
            return Err(Error::Job(format!(
                "unknown LAMMPS parameter_set {other:?}; use uff or uff4mof"
            )));
        }
    };
    let data = xtalforge_io::write_lammps(structure)?;
    let script = input_text(structure, &p1, settings, parameter_set)?;
    Ok(vec![
        super::InputFile {
            name: DATA.to_owned(),
            text: data,
        },
        super::InputFile {
            name: INPUT.to_owned(),
            text: script,
        },
    ])
}

fn input_text(
    structure: &Structure,
    p1: &P1Cell,
    settings: &Settings,
    parameter_set: ParameterSet,
) -> Result<String, Error> {
    let cutoff = settings.float("pair_cutoff")?;
    if !cutoff.is_finite() || cutoff <= 0.0 {
        return Err(Error::Job(
            "pair_cutoff must be positive and finite".to_owned(),
        ));
    }
    let symbols = util::species(&p1.atoms);
    let types = symbol_types(&symbols, parameter_set)?;
    let mut out = String::from("# Generated by xtalforge; UFF parameters from xtalforge-ff.\n");
    out.push_str("units real\natom_style full\nboundary p p p\n");
    out.push_str(&format!("read_data {DATA}\n\n"));
    out.push_str(&format!("pair_style lj/cut {cutoff:.4}\n"));
    for (i, first) in types.iter().enumerate() {
        for (j, second) in types.iter().enumerate().skip(i) {
            let (sigma, epsilon) =
                terms::vdw_pair(&first.name, &second.name).map_err(util::force_field_error)?;
            out.push_str(&format!(
                "pair_coeff {} {} {epsilon:.6} {sigma:.6}\n",
                i + 1,
                j + 1
            ));
        }
    }
    out.push_str("special_bonds lj/coul 0.0 0.0 0.0\n\n");
    let bonds = bond_types(structure, p1);
    if !bonds.is_empty() {
        out.push_str("bond_style harmonic\n");
        for (index, (first, second)) in bonds.iter().enumerate() {
            let first_type = element_type(&types, first)?;
            let second_type = element_type(&types, second)?;
            let r0 = terms::natural_bond_length(&first_type.name, &second_type.name, 1.0)
                .map_err(util::force_field_error)?;
            let force = terms::bond_force_constant(&first_type.name, &second_type.name, r0)
                .map_err(util::force_field_error)?;
            out.push_str(&format!("bond_coeff {} {force:.6} {r0:.6}\n", index + 1));
        }
        out.push('\n');
    }
    out.push_str("neighbor 2.0 bin\nneigh_modify every 1 delay 0 check yes\n");
    out.push_str(&format!(
        "thermo {}\nthermo_style custom step pe ke etotal press vol\n",
        settings.integer("thermo")?
    ));
    match settings.text("mode")? {
        "minimize" => {
            out.push_str(&format!(
                "min_style {}\nminimize {} {} {} {}\n",
                util::token(settings.text("min_style")?, "min_style")?,
                float(settings.float("energy_tol")?),
                float(settings.float("force_tol")?),
                settings.integer("max_iter")?,
                settings.integer("max_eval")?
            ));
        }
        "run" => {
            out.push_str(&format!("run {}\n", settings.integer("steps")?));
        }
        other => {
            return Err(Error::Job(format!(
                "unknown LAMMPS mode {other:?}; use minimize or run"
            )));
        }
    }
    Ok(out)
}

fn symbol_types(
    symbols: &[String],
    parameter_set: ParameterSet,
) -> Result<Vec<&'static params::UffParams>, Error> {
    let mut types = Vec::with_capacity(symbols.len());
    for symbol in symbols {
        let available =
            params::types_for_set(symbol, parameter_set).map_err(util::force_field_error)?;
        let params = available
            .iter()
            .find(|params| params.fitted)
            .copied()
            .or_else(|| available.first().copied())
            .ok_or_else(|| {
                Error::Job(format!(
                    "no {} parameters for element {symbol}",
                    parameter_set.as_str()
                ))
            })?;
        types.push(params);
    }
    Ok(types)
}

fn element_type<'a>(
    types: &[&'a params::UffParams],
    element: &str,
) -> Result<&'a params::UffParams, Error> {
    types
        .iter()
        .copied()
        .find(|params| params.element == element)
        .ok_or_else(|| Error::Job(format!("no UFF type for element {element}")))
}

/// Bond element pairs in the same order as the `xtalforge_io` data writer.
fn bond_types(structure: &Structure, p1: &P1Cell) -> Vec<(String, String)> {
    let mut site_atom: Vec<Option<usize>> = vec![None; structure.sites().len()];
    for (index, atom) in p1.atoms.iter().enumerate() {
        if let Some(slot) = site_atom.get_mut(atom.site_idx)
            && slot.is_none()
        {
            *slot = Some(index);
        }
    }
    let mut seen: BTreeSet<(usize, usize)> = BTreeSet::new();
    let mut pairs: Vec<(String, String)> = Vec::new();
    for bond in structure.explicit_bonds() {
        if bond.remove {
            continue;
        }
        let Some(i) = site_atom.get(bond.i).copied().flatten() else {
            continue;
        };
        let Some(j) = site_atom.get(bond.j).copied().flatten() else {
            continue;
        };
        if i == j || !seen.insert((i.min(j), i.max(j))) {
            continue;
        }
        let first = p1.atoms.get(i).map_or("X", |atom| atom.element.as_str());
        let second = p1.atoms.get(j).map_or("X", |atom| atom.element.as_str());
        let pair = if first <= second {
            (first.to_owned(), second.to_owned())
        } else {
            (second.to_owned(), first.to_owned())
        };
        if !pairs.contains(&pair) {
            pairs.push(pair);
        }
    }
    pairs
}

fn float(value: f64) -> String {
    if value == 0.0 {
        return "0.0".to_owned();
    }
    let text = format!("{value:.10}");
    let trimmed = text.trim_end_matches('0');
    let trimmed = trimmed.strip_suffix('.').unwrap_or(trimmed);
    trimmed.to_owned()
}
