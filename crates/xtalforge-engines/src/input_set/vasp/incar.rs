//! INCAR construction, including MAGMOM and DFT+U.

use std::collections::BTreeMap;

use serde_json::Value;
use xtalforge_core::{P1Cell, Structure};

use crate::Error;
use crate::input_set::settings::Settings;
use crate::input_set::util;

use super::vasp_float;

pub(super) fn incar_text(
    structure: &Structure,
    p1: &P1Cell,
    settings: &Settings,
) -> Result<String, Error> {
    let mut tags: BTreeMap<String, String> = BTreeMap::new();
    let title = settings.text("title")?;
    tags.insert("SYSTEM".to_owned(), quote(title));
    tags.insert(
        "PREC".to_owned(),
        util::token(settings.text("prec")?, "PREC")?.to_owned(),
    );
    tags.insert(
        "ALGO".to_owned(),
        util::token(settings.text("algo")?, "ALGO")?.to_owned(),
    );
    tags.insert("ENCUT".to_owned(), vasp_float(settings.float("encut")?));
    tags.insert("EDIFF".to_owned(), vasp_float(settings.float("ediff")?));
    tags.insert("NELM".to_owned(), settings.integer("nelm")?.to_string());
    let ispin = settings.integer("ispin")?;
    tags.insert("ISPIN".to_owned(), ispin.to_string());
    let ismear = settings.integer("ismear")?;
    tags.insert("ISMEAR".to_owned(), ismear.to_string());
    if ismear >= 0 {
        tags.insert("SIGMA".to_owned(), vasp_float(settings.float("sigma")?));
    }
    tags.insert("NSW".to_owned(), settings.integer("nsw")?.to_string());
    tags.insert("IBRION".to_owned(), settings.integer("ibrion")?.to_string());
    tags.insert("ISIF".to_owned(), settings.integer("isif")?.to_string());
    tags.insert("ICHARG".to_owned(), settings.integer("icharg")?.to_string());
    tags.insert("LREAL".to_owned(), lreal(settings)?);
    tags.insert("LWAVE".to_owned(), logical(settings.flag("lwave")?));
    tags.insert("LCHARG".to_owned(), logical(settings.flag("lcharg")?));
    tags.insert("LORBIT".to_owned(), settings.integer("lorbit")?.to_string());
    tags.insert("ADDGRID".to_owned(), logical(true));
    let ivdw = settings.integer("ivdw")?;
    if ivdw != 0 {
        tags.insert("IVDW".to_owned(), ivdw.to_string());
    }

    let (magmoms, has_magmom) = magnetic_moments(structure, p1, settings)?;
    if has_magmom && ispin < 2 {
        tags.insert("ISPIN".to_owned(), "2".to_owned());
    }
    if ispin > 1 || has_magmom {
        let text = magmoms
            .iter()
            .map(|value| format!("{value:.4}"))
            .collect::<Vec<_>>()
            .join(" ");
        tags.insert("MAGMOM".to_owned(), text);
    }

    if settings.flag("ldau")? || hubbard_present(structure, p1) {
        insert_hubbard(structure, p1, settings, &mut tags)?;
    }

    for (key, value) in settings.table("incar")? {
        let tag = incar_tag(key)?;
        tags.insert(tag, incar_value(value)?);
    }

    let mut out = String::from("# Generated by xtalforge; deterministic VASP input.\n");
    for (tag, value) in tags {
        out.push_str(&format!("{tag} = {value}\n"));
    }
    Ok(out)
}

fn magnetic_moments(
    structure: &Structure,
    p1: &P1Cell,
    settings: &Settings,
) -> Result<(Vec<f64>, bool), Error> {
    let fallback = settings.float("magmom")?;
    let mut values = Vec::with_capacity(p1.atoms.len());
    let mut found = false;
    for (index, atom) in p1.atoms.iter().enumerate() {
        let source = util::site_or_metadata(structure, atom, index, "magmom");
        let value = source.and_then(util::number).unwrap_or(fallback);
        found |= source.is_some();
        values.push(value);
    }
    Ok((values, found))
}

fn hubbard_present(structure: &Structure, p1: &P1Cell) -> bool {
    p1.atoms
        .iter()
        .enumerate()
        .any(|(index, atom)| util::site_or_metadata(structure, atom, index, "ldau_u").is_some())
}

fn insert_hubbard(
    structure: &Structure,
    p1: &P1Cell,
    settings: &Settings,
    tags: &mut BTreeMap<String, String>,
) -> Result<(), Error> {
    let default_u = settings.float("ldau_u")?;
    let default_j = settings.float("ldau_j")?;
    let default_orbital = settings.text("ldau_l")?;
    let mut orbitals = Vec::with_capacity(p1.atoms.len());
    let mut us = Vec::with_capacity(p1.atoms.len());
    let mut js = Vec::with_capacity(p1.atoms.len());
    for (index, atom) in p1.atoms.iter().enumerate() {
        let site = structure.sites().get(atom.site_idx);
        let orbital_source = site
            .and_then(|site| site.props().get("ldau_orbital"))
            .or_else(|| {
                structure
                    .metadata()
                    .get("ldau_orbital")
                    .filter(|value| !value.is_array())
            })
            .and_then(Value::as_str);
        let u_source = util::site_or_metadata(structure, atom, index, "ldau_u");
        let u = u_source.and_then(util::number).unwrap_or(default_u);
        let orbital = match orbital_source {
            Some(orbital) => util::orbital_code(orbital)?,
            None if u_source.is_none() && default_u.abs() < f64::EPSILON => -1,
            None => util::orbital_code(default_orbital)?,
        };
        orbitals.push(orbital);
        us.push(u);
        js.push(
            util::site_or_metadata(structure, atom, index, "ldau_j")
                .and_then(util::number)
                .unwrap_or(default_j),
        );
    }
    tags.insert("LDAU".to_owned(), logical(true));
    tags.insert("LDAUTYPE".to_owned(), "2".to_owned());
    tags.insert(
        "LDAUL".to_owned(),
        orbitals
            .iter()
            .map(i64::to_string)
            .collect::<Vec<_>>()
            .join(" "),
    );
    tags.insert(
        "LDAUU".to_owned(),
        us.iter()
            .map(|value| format!("{value:.4}"))
            .collect::<Vec<_>>()
            .join(" "),
    );
    tags.insert(
        "LDAUJ".to_owned(),
        js.iter()
            .map(|value| format!("{value:.4}"))
            .collect::<Vec<_>>()
            .join(" "),
    );
    tags.insert("LDAUPRINT".to_owned(), "1".to_owned());
    Ok(())
}

fn lreal(settings: &Settings) -> Result<String, Error> {
    match settings.raw("lreal") {
        Some(Value::Bool(value)) => Ok(logical(*value)),
        Some(Value::String(value)) => {
            let value = util::token(value, "LREAL")?;
            Ok(value.to_owned())
        }
        Some(_) => Err(Error::Job(
            "setting lreal must be a boolean or a string".to_owned(),
        )),
        None => Err(Error::Job("missing setting lreal".to_owned())),
    }
}

fn incar_tag(key: &str) -> Result<String, Error> {
    let tag = key.trim();
    let valid = !tag.is_empty()
        && tag
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || character == '_');
    if valid {
        Ok(tag.to_ascii_uppercase())
    } else {
        Err(Error::Job(format!("invalid INCAR tag {key:?}")))
    }
}

fn incar_value(value: &Value) -> Result<String, Error> {
    match value {
        Value::Bool(value) => Ok(logical(*value)),
        Value::Number(number) => number
            .as_f64()
            .map(vasp_float)
            .ok_or_else(|| Error::Job("INCAR number is not finite".to_owned())),
        Value::String(value) => Ok(quote(value)),
        Value::Array(values) => {
            let mut parts = Vec::with_capacity(values.len());
            for value in values {
                parts.push(incar_value(value)?);
            }
            Ok(parts.join(" "))
        }
        Value::Null => Err(Error::Job("INCAR value must not be null".to_owned())),
        Value::Object(_) => Err(Error::Job(
            "INCAR value must be a scalar or an array".to_owned(),
        )),
    }
}

fn quote(value: &str) -> String {
    let cleaned = value
        .replace(['\n', '\r', '\t'], " ")
        .replace(['#', '!'], " ")
        .replace(['/', '\\'], "_")
        .replace('"', "'")
        .trim()
        .to_owned();
    if cleaned.chars().any(char::is_whitespace) {
        format!("\"{cleaned}\"")
    } else {
        cleaned
    }
}

fn logical(value: bool) -> String {
    if value {
        ".TRUE.".to_owned()
    } else {
        ".FALSE.".to_owned()
    }
}
