//! GULP lattice-relaxation input writer (Task 18.1.5).
//!
//! The input uses the UFF library keyword, a `vectors`/`fractional` geometry
//! block and the formal site charge when present. A missing charge falls back
//! to zero, which GULP accepts; the preset can be overridden with explicit
//! charges in the structure.

use serde_json::Value;
use xtalforge_core::{P1Cell, Structure};

use crate::Error;
use crate::input_set::settings::Settings;
use crate::input_set::util;

const INPUT: &str = "gulp.gin";

pub(crate) fn build(
    structure: &Structure,
    settings: &Settings,
) -> Result<Vec<super::InputFile>, Error> {
    let p1 = structure.p1()?;
    if p1.atoms.is_empty() {
        return Err(Error::Job(
            "GULP needs a structure with at least one atom".to_owned(),
        ));
    }
    Ok(vec![super::InputFile {
        name: INPUT.to_owned(),
        text: input_text(structure, &p1, settings)?,
    }])
}

fn input_text(structure: &Structure, p1: &P1Cell, settings: &Settings) -> Result<String, Error> {
    let mut out = String::from("# Generated by xtalforge; GULP lattice relaxation.\n");
    let optimize = settings.flag("optimize")?;
    if optimize {
        if settings.flag("constant_pressure")? {
            out.push_str("opti conp\n");
        } else {
            out.push_str("opti\n");
        }
        out.push_str(&format!("maxcyc {}\n", settings.integer("max_cycles")?));
    }
    out.push_str("vectors\n");
    for row in structure.lattice().matrix() {
        for value in row {
            out.push_str(&format!("{value:.10} "));
        }
        out.pop();
        out.push('\n');
    }
    out.push_str("fractional\n");
    for atom in &p1.atoms {
        out.push_str(&format!(
            "{} {:.10} {:.10} {:.10}\n",
            atom.element, atom.frac[0], atom.frac[1], atom.frac[2]
        ));
    }
    out.push_str("species\n");
    let symbols = util::species(&p1.atoms);
    for symbol in &symbols {
        let charge = representative_charge(structure, p1, symbol)?;
        out.push_str(&format!("{symbol} core {charge:.4}\n"));
    }
    out.push_str("uff\n");
    Ok(out)
}

fn representative_charge(structure: &Structure, p1: &P1Cell, symbol: &str) -> Result<f64, Error> {
    for (index, atom) in p1.atoms.iter().enumerate() {
        if atom.element.as_str() != symbol {
            continue;
        }
        if let Some(site) = structure.sites().get(atom.site_idx)
            && let Some(charge) = site.charge()
        {
            return Ok(charge);
        }
        if let Some(charge) =
            util::site_or_metadata(structure, atom, index, "charge").and_then(Value::as_f64)
        {
            return Ok(charge);
        }
    }
    Ok(0.0)
}
